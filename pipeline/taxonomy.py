def overrides():
    """{merge: {auto: final}, category: {final: category}, drop: [...]}"""
    merge, category = {}, {}
    for cat, topics in TAXONOMY.items():
        for final, autos in topics.items():
            category[final] = cat
            for a in autos:
                assert a not in merge, f"{a} listed twice"
                merge[a] = final
    return dict(merge=merge, category=category, drop=DROP)
