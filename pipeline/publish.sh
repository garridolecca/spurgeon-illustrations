#!/bin/bash
# Publish the generated data to the `data` branch (force-pushed, single commit) and redeploy the site.
# Run from Git Bash on Windows after embed.py has written web/public/data.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/data/publish"
rm -rf "$OUT"; mkdir -p "$OUT/site" "$OUT/dataset"
cp -r "$ROOT/web/public/data/." "$OUT/site/"
gzip -c "$ROOT/data/items_tagged.jsonl" > "$OUT/dataset/illustrations.jsonl.gz"
cp "$ROOT/data/topics.json" "$OUT/dataset/topics.json"
cat > "$OUT/README.md" <<'EOF'
# Data branch

Generated by `pipeline/` on `main`; replaced (force-pushed) on every refresh.

- `site/` — the files the search app loads (`items.json`, `emb.i8` int8 vectors + `emb.scale.f32`, `passages/`, `meta.json`).
- `dataset/illustrations.jsonl.gz` — every illustration with its full record: summary, quoted original passage,
  topics, Scripture, author, sermon (title, number, date, text), book, page and Turabian citation.
- `dataset/topics.json` — the canonical topics, their category and the raw theme words grouped into each.
EOF
cd "$OUT"
git init -q -b data
git add -A
git -c user.name="garridolecca" -c user.email="garridolecca@users.noreply.github.com" commit -q -m "Data $(date '+%Y-%m-%d %H:%M')"
git push -q -f "https://github.com/garridolecca/spurgeon-illustrations.git" data
cd "$ROOT"
gh workflow run deploy.yml --repo garridolecca/spurgeon-illustrations --ref main
echo "published data and triggered deploy"
