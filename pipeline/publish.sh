#!/bin/bash
# Publish: build the site locally and force-push it to `gh-pages` (served by GitHub Pages), and force-push the
# generated dataset to `data`. Force-pushed single commits keep the repository history from growing with every
# refresh. Run from Git Bash on Windows after embed.py has written web/public/data.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="https://github.com/garridolecca/spurgeon-illustrations.git"
STAMP="$(date '+%Y-%m-%d %H:%M')"
push_dir() {   # push_dir <dir> <branch> <message>
  cd "$1"
  rm -rf .git
  git init -q -b "$2"
  git add -A
  git -c user.name="garridolecca" -c user.email="garridolecca@users.noreply.github.com" commit -q -m "$3"
  git push -q -f "$REPO" "$2"
  rm -rf .git
  cd "$ROOT"
}

# 0. derived web data (idempotent): Spanish term fixes, passage lengths, near-duplicate map (web/public/data)
export PYTHONIOENCODING=utf8 PYTHONUTF8=1
python "$ROOT/pipeline/fix_es.py"
python "$ROOT/pipeline/find_dupes.py" > "$ROOT/dupes.log"

# 1. site
cd "$ROOT/web"
[ -d node_modules ] || npm ci --no-audit --no-fund
npm run build >/dev/null
touch dist/.nojekyll
push_dir "$ROOT/web/dist" gh-pages "Site $STAMP"

# 2. dataset
OUT="$ROOT/data/publish"
rm -rf "$OUT"; mkdir -p "$OUT/dataset"
N=$(wc -l < "$ROOT/data/items_tagged.jsonl"); H=$(( (N + 1) / 2 ))   # two parts keep each file under GitHub's 100 MB limit
head -n "$H" "$ROOT/data/items_tagged.jsonl" | gzip -c > "$OUT/dataset/illustrations-1.jsonl.gz"
tail -n +"$((H + 1))" "$ROOT/data/items_tagged.jsonl" | gzip -c > "$OUT/dataset/illustrations-2.jsonl.gz"
cp "$ROOT/data/topics.json" "$OUT/dataset/topics.json"
[ -f "$ROOT/data/items_es.jsonl" ] && gzip -c "$ROOT/data/items_es.jsonl" > "$OUT/dataset/illustrations_es.jsonl.gz"
cat > "$OUT/README.md" <<'EOF'
# Data branch

Generated by `pipeline/` on `main`; replaced (force-pushed) on every refresh.

- `dataset/illustrations-1.jsonl.gz`, `illustrations-2.jsonl.gz` — (two halves, in order) every illustration with its full record: summary, quoted original passage,
  topics, categories, Scripture, author, sermon (title, number, date, text), book, page and Turabian citation.
- `dataset/illustrations_es.jsonl.gz` — Spanish translation of each illustration (summary, passage, topics), keyed by id.
- `dataset/topics.json` — the canonical topics, their category and the raw theme words grouped into each.

The live site is built from the same data and served from the `gh-pages` branch.
EOF
push_dir "$OUT" data "Data $STAMP"
echo "published site + data ($STAMP)"
